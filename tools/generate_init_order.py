#!/usr/bin/env python3
"""Generate the build-specific sorted init-entry table consumed by init_runner.c.

Finds every ``__init_*`` symbol placed in a ``.z_init_<LEVEL>_P_<prio>_SUB_<sub>_``
section across a set of relocatable objects, sorts them by (level, priority,
sub-priority), and emits an include file declaring each entry plus the sorted
pointer array ``z_init_order`` and its length ``Z_INIT_ORDER_LEN``.

Both the armclang target build and the GNU host build use this same script (and
the same sort key), so the init order no longer depends on the linker sorting
section names (armlink has no SORT, and GNU ld's SORT is lexicographic, which is
wrong for priorities like 1/5/10). The only difference is the symbol/section
dump backend.

Backends:
  fromelf  -- armclang target objects (ELF32): ``fromelf --text -s -t``.
  readelf  -- GNU host objects (ELF64): ``readelf -SW`` + ``readelf -sW``.

Usage:
  python tools/generate_init_order.py fromelf <fromelf> -o <out> <obj>...
  python tools/generate_init_order.py readelf <readelf> -o <out> <obj>...
"""

import argparse
import re
import subprocess
import sys

LEVEL_ORD = {
    "EARLY": 0,
    "PRE_KERNEL_1": 1,
    "PRE_KERNEL_2": 2,
    "POST_KERNEL": 3,
    "APPLICATION": 4,
}

# `.z_init_POST_KERNEL_P_1_SUB_0_` -> ("POST_KERNEL", 1, 0)
ZINIT_RE = re.compile(r"z_init_([A-Z0-9_]+)_P_(\d+)_SUB_(\d+)_")

HEADER = """\
/* GENERATED FILE -- DO NOT EDIT.
 *
 * Sorted init-entry table, generated by tools/generate_init_order.py.
 * Order key: (init level, priority, sub-priority).
 */
"""


def _key(entry):
    # entry == (symbol, level, prio, sub)
    return (LEVEL_ORD[entry[1]], entry[2], entry[3], entry[0])


def fromelf_entries(tool, obj):
    res = subprocess.run([tool, "--text", "-s", "-t", obj],
                         capture_output=True, text=True)
    if res.returncode != 0:
        print(f"fromelf failed on {obj}:\n{res.stderr}", file=sys.stderr)
        return None
    # Section index -> (level, prio, sub)
    sections = {}
    for m in re.finditer(r"\*\* Section #(\d+) '([^']*)'", res.stdout):
        z = ZINIT_RE.search(m.group(2))
        if z and z.group(1) in LEVEL_ORD:
            sections[int(m.group(1))] = (z.group(1), int(z.group(2)), int(z.group(3)))
    entries = []
    # Symbol-table row: "<n>  <name>  <value>  <bind>  <sec>  <type>  <vis>  <size>"
    for line in res.stdout.splitlines():
        parts = line.split()
        if (len(parts) >= 5 and parts[1].startswith("__init_")
                and parts[4].isdigit()):
            sec = int(parts[4])
            if sec in sections:
                entries.append((parts[1],) + sections[sec])
    return entries


def readelf_entries(tool, obj):
    sw = subprocess.run([tool, "-SW", obj], capture_output=True, text=True)
    sW = subprocess.run([tool, "-sW", obj], capture_output=True, text=True)
    if sw.returncode != 0 or sW.returncode != 0:
        print(f"readelf failed on {obj}", file=sys.stderr)
        return None
    sections = {}
    for m in re.finditer(r"^\s*\[\s*(\d+)\]\s+(\S+)", sw.stdout, re.MULTILINE):
        z = ZINIT_RE.search(m.group(2))
        if z and z.group(1) in LEVEL_ORD:
            sections[int(m.group(1))] = (z.group(1), int(z.group(2)), int(z.group(3)))
    entries = []
    # "<Num>: <Value> <Size> <Type> <Bind> <Vis> <Ndx> <Name>"
    for line in sW.stdout.splitlines():
        parts = line.split()
        if (len(parts) >= 8 and parts[-1].startswith("__init_")
                and parts[-2].isdigit()):
            sec = int(parts[-2])
            if sec in sections:
                entries.append((parts[-1],) + sections[sec])
    return entries


def main(argv):
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("backend", choices=["fromelf", "readelf"])
    ap.add_argument("tool", help="path to fromelf/readelf")
    ap.add_argument("-o", "--out", required=True, help="output .inc path")
    ap.add_argument("objects", nargs="+", help="relocatable .o files to scan")
    args = ap.parse_args(argv)

    fn = fromelf_entries if args.backend == "fromelf" else readelf_entries
    seen = {}
    for obj in args.objects:
        entries = fn(args.tool, obj)
        if entries is None:
            return 1
        for e in entries:
            if e[0] in seen and seen[e[0]] != e:
                print(f"conflicting init entry {e[0]}: {seen[e[0]]} vs {e}",
                      file=sys.stderr)
                return 1
            seen[e[0]] = e

    ordered = sorted(seen.values(), key=_key)
    if not ordered:
        print("ERROR: no __init_* entries found", file=sys.stderr)
        return 1

    lines = [HEADER]
    for sym, *_ in ordered:
        lines.append(f"extern const struct init_entry {sym};")
    lines.append("")
    lines.append("const struct z_init_entry z_init_order[] = {")
    for sym, level, _prio, _sub in ordered:
        lines.append(f"\t{{ Z_INIT_ORD_{level}, &{sym} }},")
    lines.append("};")
    lines.append("")
    lines.append(f"#define Z_INIT_ORDER_LEN {len(ordered)}u")
    lines.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"{args.out}: {len(ordered)} init entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
